/**
 * תקרות אורך לשדות טקסט חופשי.
 *
 * למה זה נחוץ: עמודות `String` ב-Postgres הן `text` — אין להן תקרה משלהן.
 * טופס שנשלח ישירות (או action id שנקרא מתוך חבילת הלקוח) יכול לשמור
 * מגה-בייטים בשדה יחיד. התוצאה אינה רק מסד נתונים מנופח: אותם ערכים מוזנים
 * חזרה לעמוד הציבורי, להודעות WhatsApp ולאימיילים, ולכן שורה אחת מנופחת
 * מאטה או מפילה מסכים שלמים — וזה נגיש לכל בעלת חשבון.
 *
 * הבדיקה נעשית בשרת בלבד. תכונת `maxLength` ב-HTML היא נוחות למשתמשת,
 * ולא אכיפה: היא לא קיימת עבור מי שלא עוברת דרך הדפדפן.
 */

/** תקרות משותפות, לפי אופי השדה. */
export const TEXT_LIMITS = {
  /** שם אדם / עסק / שירות — שורה אחת קצרה. */
  name: 120,
  /** שדה קצר: עיר, כתובת, כותרת תמונה. */
  short: 200,
  /** פסקה: תיאור, הודעת פתיחה. */
  paragraph: 2000,
  /** הערות פנימיות — ארוכות יותר, אך עדיין חסומות. */
  notes: 5000,
  /** כתובת אימייל. */
  email: 254,
} as const;

/**
 * מחזיר true כאשר הערך חורג מהתקרה. ההשוואה היא על אורך המחרוזת אחרי trim,
 * כך שרווחים בקצוות אינם נחשבים.
 */
export function exceedsLimit(value: string, limit: number): boolean {
  return value.trim().length > limit;
}

/** הודעת שגיאה אחידה בעברית עבור שדה שחרג מהתקרה. */
export function tooLongError(limit: number): string {
  return `הטקסט ארוך מדי — עד ${limit} תווים`;
}
